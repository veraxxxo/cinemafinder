// Сшивка названий афиши с точками OpenStreetMap.
//
// Раньше эта логика жила прямо в fetch-schedule.mjs, а тест держал её копию —
// и копия разошлась с оригиналом настолько, что тест был зелёный при сломанной
// сшивке. Теперь модуль один на обоих.
//
// Ловушка, ради которой всё переписано: в OSM полно точек, названных просто
// брендом — «Мираж» ×3, «Люксор» ×4, «Киномакс» ×3, «Каро» ×2, почти все без
// адреса. Прежний проход искал совпадение по подстроке, и любой зал сети
// («Мираж Синема Реутов») приклеивался к случайной из этих точек. В данных за
// 09.08 это выглядело как 90 сеансов в одном «Мираже» и 11 площадок на весь
// город при 219 сеансах.
//
// Правило простое: точка, у которой в названии нет ничего, кроме сети, не
// может представлять конкретный зал. Такой площадке достаётся только имя,
// которое само состоит из одной сети.

import { normName } from './util.mjs';
import { bestMatch } from './match.mjs';

/**
 * Возвращает функцию `имя → кинотеатр | null`.
 * Два прохода: точное совпадение нормализованных названий, затем совпадение
 * различающей части (bestMatch сам отбрасывает кандидатов без такой части и
 * не смешивает разные сети).
 */
export function makeCinemaMatcher(cinemas) {
  const exact = new Map();
  for (const c of cinemas) {
    const key = normName(c.name);
    if (key && !exact.has(key)) exact.set(key, c);
  }

  const cache = new Map();

  return function match(rawName) {
    if (cache.has(rawName)) return cache.get(rawName);

    const key = normName(rawName);
    let hit = (key && exact.get(key)) || null;
    if (!hit) hit = bestMatch(rawName, cinemas)?.item ?? null;

    cache.set(rawName, hit);
    return hit;
  };
}
